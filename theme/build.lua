-- lazygit, read after lazygit/config.yml (LG_CONFIG_FILE in zsh/.zshenv).
-- Panel titles are drawn in the border colors, so inactive panels get VS Code's inactive-title
-- gray: its border gray would hide their titles.
local function color(...)
  return "[" .. table.concat(vim.tbl_map(function(v)
    return v:sub(1, 1) == "#" and ('"' .. v .. '"') or v
  end, { ... }), ", ") .. "]"
end
local lazygit = {
  { "activeBorderColor", color(p.focus, "bold") },
  { "inactiveBorderColor", color(p.dim) },
  { "searchingActiveBorderColor", color(p.yellow, "bold") },
  { "optionsTextColor", color(p.blue) }, -- key hints at the bottom
  { "selectedLineBgColor", color(over(p.list_selection, p.panel)) }, -- as in VS Code's side bar
  { "inactiveViewSelectedLineBgColor", color(p.list_selection_inactive) },
  { "cherryPickedCommitFgColor", color(p.on_button) }, -- copied commits look like buttons
