local function esc(v)
  return (v:gsub("&", "&amp;"):gsub("<", "&lt;"):gsub(">", "&gt;"))
end
local function settings(t, indent)
  local out = { indent .. "<key>settings</key>", indent .. "<dict>" }
  for _, k in ipairs({ "background", "foreground", "fontStyle" }) do
    if t[k] then
      vim.list_extend(out, { indent .. "\t<key>" .. k .. "</key>", indent .. "\t<string>" .. esc(t[k]) .. "</string>" })
    end
  end
  out[#out + 1] = indent .. "</dict>"
  return out
end
local tm = {
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
  "<!-- " .. header .. " -->",
  '<plist version="1.0">',
  "<dict>",
  "\t<key>name</key>",
  "\t<string>Dark 2026</string>",
  "\t<key>settings</key>",
  "\t<array>",
  "\t\t<dict>",
}
vim.list_extend(tm, settings({ background = p.bg, foreground = p.fg }, "\t\t\t"))
tm[#tm + 1] = "\t\t</dict>"
for _, rule in ipairs(scopes) do
  local fg = rule.fg and assert(s[rule.fg], "no syntax color " .. rule.fg .. " in palette.lua")
  local scope = "\t\t\t<string>" .. esc(table.concat(rule, ", ")) .. "</string>"
  vim.list_extend(tm, { "\t\t<dict>", "\t\t\t<key>scope</key>", scope })
  vim.list_extend(tm, settings({ foreground = fg, fontStyle = rule.style }, "\t\t\t"))
  tm[#tm + 1] = "\t\t</dict>"
end
vim.list_extend(tm, { "\t</array>", "</dict>", "</plist>" })
files["dark2026.tmTheme"] = tm

-- Write (or with --check, compare) each file
local check, stale = arg[1] == "--check", {}
local names = vim.tbl_keys(files)
table.sort(names)
for _, name in ipairs(names) do
  local path, want = dir .. "/" .. name, files[name]
  local ok, have = pcall(vim.fn.readfile, path)
  if not ok or not vim.deep_equal(have, want) then
    stale[#stale + 1] = name
    if not check then
      vim.fn.writefile(want, path)
      print("wrote theme/" .. name)
    end
  end
end
if check then
  if #stale > 0 then
    io.stderr:write("out of date: " .. table.concat(stale, ", ") .. " (run nvim -l ~/.config/theme/build.lua)\n")
    os.exit(1)
  end
  return
end
if #stale == 0 then
  print("theme files already up to date")
end
-- bat and delta read themes from bat's cache, not from the file: rebuild it when it's older
if vim.fn.executable("bat") == 1 then
  local cache = vim.trim(vim.fn.system({ "bat", "--cache-dir" })) .. "/themes.bin"
  if vim.fn.getftime(dir .. "/dark2026.tmTheme") >= vim.fn.getftime(cache) then
    vim.fn.system({ "bat", "cache", "--build" })
    print(vim.v.shell_error == 0 and "rebuilt bat's theme cache" or "bat cache --build failed")
  end
end
